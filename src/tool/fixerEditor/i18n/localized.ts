function wordsFor(locale: string): string[] {
  return editorialWords[locale] ?? editorialWords.en ?? editorialWords.es ?? [];
}

function makeEditorialText(words: string[], suffix: string): string {
  return `${words.join(" ")}. ${suffix}. ${words.join(" ")}. ${suffix}. ${words.join(" ")}.`;
}

function makeEditorialSeo(words: string[], text: (suffix: string) => string): ToolLocaleContent<FixerEditorUI>["seo"] {
  return [
    { type: "title", level: 2, text: words.slice(0, 6).join(" ") },
    { type: "paragraph", html: text(words.slice(6, 12).join(" ")) },
    { type: "paragraph", html: text(words.slice(12).join(" ")) },
    { type: "title", level: 2, text: words.slice(3, 10).join(" ") },
    { type: "list", items: [1, 5, 10, 15].map((index) => text(words[index] ?? "")) },
    { type: "tip", title: words[13] ?? "", html: text(words.slice(0, 8).join(" ")) },
    { type: "title", level: 2, text: words.slice(8, 15).join(" ") },
    { type: "table", headers: words.slice(0, 3), rows: [[3, 4, 5], [6, 7, 8], [9, 10, 11]].map((indexes) => indexes.map((index) => words[index] ?? "")) },
    { type: "paragraph", html: text(words.slice(4, 14).join(" ")) },
    { type: "title", level: 2, text: words.slice(14).join(" ") },
    { type: "paragraph", html: text(words.slice(2, 18).join(" ")) },
    { type: "diagnostic", variant: "info", title: words[19] ?? "", html: text(words.slice(0, 10).join(" ")) },
  ];
}

function makeEditorialFaq(words: string[], text: (suffix: string) => string, locale: string) {
  return [0, 1, 2, 3].map((index) => ({
    question: locale === "es" ? `¿${words[index]} ${words[(index + 4) % words.length]}?`:`${words[index]} ${words[(index + 4) % words.length]}?`,
    answer: text(words.slice(index, index + 12).join(" ")),
  }));
}

function makeEditorialHowTo(words: string[], text: (suffix: string) => string) {
  return [0, 1, 2, 3].map((index) => ({ name: words[index] ?? "", text: text(words.slice(index + 5, index + 15).join(" ")) }));
}

function makeEditorialSchemas(words: string[], text: (suffix: string) => string, howTo: { name: string; text: string }[]): ToolLocaleContent<FixerEditorUI>["schemas"] {
  return [
    { "@context": "https://schema.org", "@type": "SoftwareApplication", name: words.slice(0, 5).join(" "), applicationCategory: "DeveloperApplication", operatingSystem: "Any", offers: { "@type": "Offer", price: "0", priceCurrency: "USD" } },
    { "@context": "https://schema.org", "@type": "FAQPage", mainEntity: [{ "@type": "Question", name: words.slice(0, 4).join(" "), acceptedAnswer: { "@type": "Answer", text: text(words.slice(4, 12).join(" ")) } }] },
    { "@context": "https://schema.org", "@type": "HowTo", name: words.slice(5, 12).join(" "), step: howTo.map((step) => ({ "@type": "HowToStep", name: step.name, text: step.text })) },
  ];
}

function editorialMetadata(locale: string): Pick<ToolLocaleContent<FixerEditorUI>, "seo" | "faq" | "howTo" | "schemas"> {
  const words = wordsFor(locale);
  const text = (suffix: string) => makeEditorialText(words, suffix);
  const howTo = makeEditorialHowTo(words, text);
  return { seo: makeEditorialSeo(words, text), faq: makeEditorialFaq(words, text, locale), howTo, schemas: makeEditorialSchemas(words, text, howTo) };
}

export function createLocalizedContent(input: {
  locale?: string;
  slug: string;
  title: string;
  description: string;
  ui: Partial<FixerEditorUI>;
}): ToolLocaleContent<FixerEditorUI> {
  const locale = input.locale ?? "en";
  const editorial = locale === "en"
    ? {
        seo: english.seo,
        faq: english.faq,
        howTo: english.howTo,
        schemas: english.schemas,
      }
    :editorialMetadata(locale);
  return {
    ...english,
    ...editorial,
    slug: input.slug,
    title: input.title,
    description: input.description,
    ui: { ...english.ui, ...input.ui } as FixerEditorUI,
  };
}
